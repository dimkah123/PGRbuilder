export const DECLENSION_TO_BASE = new Map();

/**
 * Generates grammatical declension variants for a Russian word or term.
 * @param {string} word - Base term in Russian
 * @returns {string[]} Array of inflected forms
 */
export function generateRussianDeclensions(word) {
    if (!word || word.length < 3) return [];
    if (!/[а-яёА-ЯЁ]/.test(word)) return [];

    const forms = new Set();
    const w = word.trim();
    const lower = w.toLowerCase();
    const isCap = w[0] === w[0].toUpperCase();

    const addForm = (form) => {
        const adjusted = isCap ? form.charAt(0).toUpperCase() + form.slice(1) : form;
        forms.add(adjusted);
        if (!DECLENSION_TO_BASE.has(form.toLowerCase())) {
            DECLENSION_TO_BASE.set(form.toLowerCase(), w);
        }
    };

    // 1. Irregular/predefined forms
    if (IRREGULAR_DECLENSIONS[lower]) {
        IRREGULAR_DECLENSIONS[lower].forEach(f => addForm(f));
    }

    // 2. Standard Russian noun endings
    if (lower.endsWith('ия')) {
        const stem = w.slice(0, -2);
        ['ии', 'ию', 'ией', 'иею'].forEach(e => addForm(stem + e));
    } else if (lower.endsWith('а')) {
        const stem = w.slice(0, -1);
        const lastStemChar = lower.slice(-2, -1);
        const isVelarOrSibilant = ['г', 'к', 'х', 'ж', 'ч', 'ш', 'щ'].includes(lastStemChar);
        const genitiveEnding = isVelarOrSibilant ? 'и' : 'ы';
        [genitiveEnding, 'е', 'у', 'ой', 'ою'].forEach(e => addForm(stem + e));
    } else if (lower.endsWith('я')) {
        const stem = w.slice(0, -1);
        ['и', 'е', 'ю', 'ей', 'ёй'].forEach(e => addForm(stem + e));
    } else if (lower.endsWith('ие')) {
        const stem = w.slice(0, -2);
        ['ия', 'ию', 'ием', 'ии'].forEach(e => addForm(stem + e));
    } else if (lower.endsWith('ь')) {
        const stem = w.slice(0, -1);
        ['я', 'ю', 'ем', 'е', 'и', 'ью'].forEach(e => addForm(stem + e));
    } else if (/[бвгджзклмнпрстфхцчшщ]$/i.test(w)) {
        ['а', 'у', 'ом', 'е', 'ы', 'ов', 'ам', 'ами', 'ах'].forEach(e => addForm(w + e));
    }

    return [...forms];
}
